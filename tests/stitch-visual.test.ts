test('alpha-only delta fails when RGB channels remain identical', async () => {
  // Given: one pixel whose alpha changes, with identical RGB.
  const { comparePixels } = await import('../scripts/visual/pixels.js');
  const reference = await sharp(Buffer.from([255, 0, 0, 255]), { raw: { width: 1, height: 1, channels: 4 } }).png().toBuffer();
  const actual = await sharp(Buffer.from([255, 0, 0, 254]), { raw: { width: 1, height: 1, channels: 4 } }).png().toBuffer();
  // When: compare without tolerance.
  const report = await comparePixels(reference, actual);
  // Then: alpha cannot silently disappear from the comparison.
  assert.equal(report.pass, false);
  assert.equal(report.changedPixels, 1);
  assert.equal(report.ratio, 1);
});

