for (const scenario of [
  { name: 'repo-only without OneDrive', source: false, missing: true, damage: '', code: 0, integrity: 'REPOSITORY_VERIFIED' },
  { name: 'explicit intact source', source: true, missing: false, damage: '', code: 0, integrity: 'REPOSITORY_AND_EXTERNAL_VERIFIED' },
  { name: 'explicit missing source', source: true, missing: true, damage: '', code: 2, integrity: 'INPUT_OUTPUT_ERROR' },
  ...['inicio_membego/screen.png', 'inicio_membego/code.html', 'retail_commercial_mobile/DESIGN.md'].flatMap((damage) => [
    { name: `repo drift ${damage}`, source: false, missing: true, damage, code: 2, integrity: 'REFERENCE_DRIFT' },
    { name: `explicit source drift ${damage}`, source: true, missing: false, damage, code: 2, integrity: 'REFERENCE_DRIFT' },
  ]),
]) {
  test(`Node portability when ${scenario.name}`, { concurrency: true }, async (t) => {
    // Given: a checkout fixture with unchanged pinned assets/hashes and an unavailable provenance location.
    await mkdir('.omo/start-work/r0-visual', { recursive: true });
    const dir = resolve(await mkdtemp('.omo/start-work/r0-visual/test-portability-'));
    t.after(() => rm(dir, { recursive: true, force: true }));
    const docs = join(dir, 'docs/transformacion-membego');
    await mkdir(docs, { recursive: true });
    await cp('docs/transformacion-membego/stitch', join(docs, 'stitch'), { recursive: true });
    const manifest = z.object({ source_root: z.string() }).passthrough()
      .parse(JSON.parse(await readFile('docs/transformacion-membego/stitch-manifest.json', 'utf8')));
    await writeFile(join(docs, 'stitch-manifest.json'), JSON.stringify({ ...manifest, source_root: join(dir, 'OneDrive-absent') }));
    const source = join(dir, 'source');
    if (!scenario.missing) await cp(join(docs, 'stitch'), source, { recursive: true });
    if (scenario.damage) await writeFile(join(scenario.source ? source : join(docs, 'stitch'), scenario.damage), 'drift');
    const actual = resolve('docs/transformacion-membego/stitch/inicio_membego/screen.png');
    const metadata = await sharp(await readFile(actual)).metadata();
    await writeFile(join(dir, 'metadata.json'), JSON.stringify({ label: 'APPLICATION_CAPTURE',
      sha256: createHash('sha256').update(await readFile(actual)).digest('hex'), browser: 'contract-fixture', version: 'test',
      viewport: { width: metadata.width, height: metadata.height }, dpr: 1, locale: 'en-US', timezone: 'UTC',
      fontsReady: true, animationPolicy: 'disabled', scale: 'css', fullPage: false, capturedAt: '2026-01-01T00:00:00.000Z' }));
    await mkdir(join(dir, '.omo/start-work/r0-visual'), { recursive: true });
    const env: NodeJS.ProcessEnv = { ...process.env, PATH: '' };
    for (const key of Object.keys(env)) if (key.toLowerCase() === 'path') env[key] = '';
    // When: the installed Node/tsx CLI runs with no executable discoverable on PATH.
    const result = spawnSync(process.execPath, [tsxCli, resolve('scripts/visual/compare.ts'), '--screen', 'inicio_membego',
      '--actual', actual, '--metadata', 'metadata.json', '--out', '.omo/start-work/r0-visual/result',
      ...(scenario.source ? ['--source-root', source] : [])], { cwd: dir, env, encoding: 'utf8', timeout: 30_000 });
    // Then: portability never bypasses pinned hashes; this contract fixture never grants app fidelity.
    assert.equal(result.status, scenario.code, result.stdout + result.stderr);
    const report = z.object({ reason: z.string(), referenceIntegrity: z.string().optional(), fidelityApproval: z.literal('NOT_GRANTED') })
      .parse(JSON.parse(result.stdout));
    assert.equal(report.referenceIntegrity ?? report.reason, scenario.integrity);
  });
}

test('reference metadata matches when reading the twelve recorded PNGs', async () => {
  // Given: the existing manifest, never regenerated by this test.
  const manifest = z.object({
    capture_metadata: z.object({ css_viewport: z.null(), device_pixel_ratio: z.null(), export_scale: z.null() }),
    screens: z.array(z.object({ id: z.string(), png: z.object({
      path: z.string(), sha256: z.string(), width: z.number(), height: z.number(),
    }) })).length(12),
  }).parse(JSON.parse(await readFile('docs/transformacion-membego/stitch-manifest.json', 'utf8')));
  // When: decode and hash the actual versioned bytes.
  const observations = await Promise.all(manifest.screens.map(async ({ id, png }) => {
    const bytes = await readFile(png.path);
    const metadata = await sharp(bytes).metadata();
    return { id, hash: createHash('sha256').update(bytes).digest('hex'),
      width: metadata.width, height: metadata.height, expected: png };
  }));
  // Then: metadata describes bytes, not an invented CSS viewport.
  assert.equal(new Set(observations.map(({ id }) => id)).size, 12);
  for (const observation of observations) {
    assert.equal(observation.hash, observation.expected.sha256);
    assert.equal(observation.width, observation.expected.width);
    assert.equal(observation.height, observation.expected.height);
  }
});

