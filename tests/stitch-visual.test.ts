const scenarios = [
  { name: 'identical', actual: 'same.png', options: [], code: 0, reason: 'PIXELS_EQUAL', changed: 0 },
  { name: 'changed', actual: 'changed.png', options: [], code: 1, reason: 'PIXEL_MISMATCH', changed: 1 },
  { name: 'size', actual: 'size.png', options: [], code: 1, reason: 'DIMENSION_MISMATCH', changed: null },
  { name: 'corrupt', actual: 'corrupt.png', options: [], code: 2, reason: 'INVALID_IMAGE' },
  { name: 'explicit tolerance', actual: 'changed.png', options: ['--max-ratio', '0.01'], code: 0, reason: 'WITHIN_EXPLICIT_TOLERANCE', changed: 1 },
  { name: 'excess tolerance', actual: 'same.png', options: ['--max-ratio', '1'], code: 2, reason: 'INVALID_ARGUMENT' },
  { name: 'negative tolerance', actual: 'same.png', options: ['--max-ratio', '-1'], code: 2, reason: 'INVALID_ARGUMENT' },
  { name: 'nonfinite tolerance', actual: 'same.png', options: ['--max-ratio', 'NaN'], code: 2, reason: 'INVALID_ARGUMENT' },
] as const;

for (const scenario of scenarios) {
  test(`comparison enforces its contract when ${scenario.name}`, async (t) => {
    // Given: isolated real PNG files; only one of 100 pixels is altered.
    await mkdir('.omo/start-work/r0-visual', { recursive: true });
    const dir = await mkdtemp('.omo/start-work/r0-visual/test-');
    t.after(() => rm(dir, { recursive: true, force: true }));
    const raw = Buffer.alloc(400, 255);
    await sharp(raw, { raw: { width: 10, height: 10, channels: 4 } }).png().toFile(join(dir, 'same.png'));
    raw[0] = 0;
    await sharp(raw, { raw: { width: 10, height: 10, channels: 4 } }).png().toFile(join(dir, 'changed.png'));
    await sharp({ create: { width: 11, height: 10, channels: 4, background: '#fff' } }).png().toFile(join(dir, 'size.png'));
    await writeFile(join(dir, 'corrupt.png'), 'not an image');
    // When: run the actual public CLI, not a mocked adapter.
    const result = spawnSync(process.execPath, [tsxCli, 'scripts/visual/compare.ts',
      '--self-test-reference', join(dir, 'same.png'), '--actual', join(dir, scenario.actual),
      '--out', join(dir, 'result'), ...scenario.options], { encoding: 'utf8' });
    // Then: exit status and machine-readable result distinguish the failure.
    assert.equal(result.status, scenario.code, result.stderr);
    const report = z.object({ reason: z.string(), changedPixels: z.number().nullable().optional(),
      totalPixels: z.number().optional(), ratio: z.number().nullable().optional(), referenceHash: z.string().optional(), actualHash: z.string().optional(),
      tolerance: z.number().optional(), label: z.string().optional(), diffArtifact: z.string().nullable().optional(),
    }).parse(JSON.parse(result.stdout));
    assert.equal(report.reason, scenario.reason);
    if ('changed' in scenario) {
      assert.equal(report.changedPixels, scenario.changed);
      assert.equal(report.label, 'TOOLING_SELF_TEST');
      assert.equal(report.tolerance, scenario.options.length ? 0.01 : 0);
      assert.equal(report.totalPixels, 100);
      assert.equal(report.ratio, scenario.changed === null ? null : scenario.changed / 100);
      assert.equal(report.referenceHash, createHash('sha256').update(await readFile(join(dir, 'same.png'))).digest('hex'));
      assert.equal(report.actualHash, createHash('sha256').update(await readFile(join(dir, scenario.actual))).digest('hex'));
      if (report.diffArtifact) assert.equal((await sharp(await readFile(report.diffArtifact)).metadata()).width, 10);
    }
  });
}

